'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = process.env.VPN_UI_SOURCE || path.join(__dirname, '../router-reinstall-kit/files/opt/router-control/www');
const { parse, serialize } = require(path.join(root, 'vpn.js'));
const text = '# ordered mirrors\n[first] # preserve header comment\nhttps://example.org/sub\n# mirror comment\nhttps://mirror.example.org/sub\n\n[second]\nhttps://example.net/sub\n';
const model = parse(text);
assert.equal(model.groups.length, 2);
assert.equal(serialize(model), text);
model.groups.reverse();
model.groups[0].name = 'renamed';
assert.ok(serialize(model).indexOf('[renamed]') < serialize(model).indexOf('[first]'));
assert.ok(serialize(model).includes('# mirror comment'));
model.groups.splice(1, 1);
assert.equal(parse(serialize(model)).groups.length, 1);
model.groups.push({ name: 'added', comment: '', lines: ['https://example.com/sub'] });
assert.equal(parse(serialize(model)).groups[1].name, 'added');
assert.equal(serialize(parse('')), '\n');
const source = fs.readFileSync(path.join(root, 'cgi-bin/router-control'), 'utf8');
for (const match of source.matchAll(/<script>([\s\S]*?)<\/script>/g)) new Function(match[1]);
assert.ok(source.indexOf('/vpn.css') > source.indexOf('</style>'));
assert.ok(source.includes('data-saved-revision'));
console.log('PASS: editor add/edit/remove/reorder, comments roundtrip, inline JS syntax, responsive stylesheet order');
